// Four f32 dot products sharing x. The accumulation tree intentionally
// matches dotF32 so grouped and separate attention remain numerically stable.
// func dotF32x4(q0, q1, q2, q3, x *float32, n int) (s0, s1, s2, s3 float32)
TEXT ·dotF32x4(SB), NOSPLIT|NOFRAME, $0-64
	MOVD q0+0(FP), R0
	MOVD q1+8(FP), R1
	MOVD q2+16(FP), R2
	MOVD q3+24(FP), R3
	MOVD x+32(FP), R4
	MOVD n+40(FP), R5

	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16
	VEOR V8.B16, V8.B16, V8.B16
	VEOR V9.B16, V9.B16, V9.B16
	VEOR V10.B16, V10.B16, V10.B16
	VEOR V11.B16, V11.B16, V11.B16
	VEOR V12.B16, V12.B16, V12.B16
	VEOR V13.B16, V13.B16, V13.B16
	VEOR V14.B16, V14.B16, V14.B16
	VEOR V15.B16, V15.B16, V15.B16
	FMOVS $(1.0), F31
	VDUP V31.S[0], V31.S4

	CMP $16, R5
	BLT dot4_reduce

dot4_loop16:
	VLD1.P 16(R4), [V16.S4]
	VLD1.P 16(R4), [V17.S4]
	VLD1.P 16(R4), [V18.S4]
	VLD1.P 16(R4), [V19.S4]

	VLD1.P 16(R0), [V20.S4]
	VLD1.P 16(R0), [V21.S4]
	VLD1.P 16(R0), [V22.S4]
	VLD1.P 16(R0), [V23.S4]
	VFMLA V20.S4, V16.S4, V0.S4
	VFMLA V21.S4, V17.S4, V1.S4
	VFMLA V22.S4, V18.S4, V2.S4
	VFMLA V23.S4, V19.S4, V3.S4

	VLD1.P 16(R1), [V20.S4]
	VLD1.P 16(R1), [V21.S4]
	VLD1.P 16(R1), [V22.S4]
	VLD1.P 16(R1), [V23.S4]
	VFMLA V20.S4, V16.S4, V4.S4
	VFMLA V21.S4, V17.S4, V5.S4
	VFMLA V22.S4, V18.S4, V6.S4
	VFMLA V23.S4, V19.S4, V7.S4

	VLD1.P 16(R2), [V20.S4]
	VLD1.P 16(R2), [V21.S4]
	VLD1.P 16(R2), [V22.S4]
	VLD1.P 16(R2), [V23.S4]
	VFMLA V20.S4, V16.S4, V8.S4
	VFMLA V21.S4, V17.S4, V9.S4
	VFMLA V22.S4, V18.S4, V10.S4
	VFMLA V23.S4, V19.S4, V11.S4

	VLD1.P 16(R3), [V20.S4]
	VLD1.P 16(R3), [V21.S4]
	VLD1.P 16(R3), [V22.S4]
	VLD1.P 16(R3), [V23.S4]
	VFMLA V20.S4, V16.S4, V12.S4
	VFMLA V21.S4, V17.S4, V13.S4
	VFMLA V22.S4, V18.S4, V14.S4
	VFMLA V23.S4, V19.S4, V15.S4

	SUB $16, R5, R5
	CMP $16, R5
	BGE dot4_loop16

dot4_reduce:
	VFMLA V1.S4, V31.S4, V0.S4
	VFMLA V2.S4, V31.S4, V0.S4
	VFMLA V3.S4, V31.S4, V0.S4
	VFMLA V5.S4, V31.S4, V4.S4
	VFMLA V6.S4, V31.S4, V4.S4
	VFMLA V7.S4, V31.S4, V4.S4
	VFMLA V9.S4, V31.S4, V8.S4
	VFMLA V10.S4, V31.S4, V8.S4
	VFMLA V11.S4, V31.S4, V8.S4
	VFMLA V13.S4, V31.S4, V12.S4
	VFMLA V14.S4, V31.S4, V12.S4
	VFMLA V15.S4, V31.S4, V12.S4

	VMOV V0.S[0], R6
	VMOV V0.S[1], R7
	VMOV V0.S[2], R8
	VMOV V0.S[3], R9
	FMOVS R6, F24
	FMOVS R7, F20
	FMOVS R8, F21
	FMOVS R9, F22
	FADDS F20, F24
	FADDS F22, F21
	FADDS F21, F24

	VMOV V4.S[0], R6
	VMOV V4.S[1], R7
	VMOV V4.S[2], R8
	VMOV V4.S[3], R9
	FMOVS R6, F25
	FMOVS R7, F20
	FMOVS R8, F21
	FMOVS R9, F22
	FADDS F20, F25
	FADDS F22, F21
	FADDS F21, F25

	VMOV V8.S[0], R6
	VMOV V8.S[1], R7
	VMOV V8.S[2], R8
	VMOV V8.S[3], R9
	FMOVS R6, F26
	FMOVS R7, F20
	FMOVS R8, F21
	FMOVS R9, F22
	FADDS F20, F26
	FADDS F22, F21
	FADDS F21, F26

	VMOV V12.S[0], R6
	VMOV V12.S[1], R7
	VMOV V12.S[2], R8
	VMOV V12.S[3], R9
	FMOVS R6, F27
	FMOVS R7, F20
	FMOVS R8, F21
	FMOVS R9, F22
	FADDS F20, F27
	FADDS F22, F21
	FADDS F21, F27

	CBZ R5, dot4_done

dot4_tail:
	FMOVS.P 4(R4), F16
	FMOVS.P 4(R0), F17
	FMULS F16, F17, F18
	FADDS F18, F24
	FMOVS.P 4(R1), F17
	FMULS F16, F17, F18
	FADDS F18, F25
	FMOVS.P 4(R2), F17
	FMULS F16, F17, F18
	FADDS F18, F26
	FMOVS.P 4(R3), F17
	FMULS F16, F17, F18
	FADDS F18, F27
	SUB $1, R5, R5
	CBNZ R5, dot4_tail

dot4_done:
	FMOVS F24, s0+48(FP)
	FMOVS F25, s1+52(FP)
	FMOVS F26, s2+56(FP)
	FMOVS F27, s3+60(FP)
	RET

// Four f32 AXPYs sharing x.
// func axpyF32x4(out0, out1, out2, out3 *float32, a0, a1, a2, a3 float32, x *float32, n int)
TEXT ·axpyF32x4(SB), NOSPLIT|NOFRAME, $0-64
	MOVD out0+0(FP), R0
	MOVD out1+8(FP), R1
	MOVD out2+16(FP), R2
	MOVD out3+24(FP), R3
	MOVD R0, R6
	MOVD R1, R7
	MOVD R2, R8
	MOVD R3, R9
	FMOVS a0+32(FP), F24
	FMOVS a1+36(FP), F25
	FMOVS a2+40(FP), F26
	FMOVS a3+44(FP), F27
	MOVD x+48(FP), R4
	MOVD n+56(FP), R5
	VDUP V24.S[0], V24.S4
	VDUP V25.S[0], V25.S4
	VDUP V26.S[0], V26.S4
	VDUP V27.S[0], V27.S4

	CMP $16, R5
	BLT axpy4_loop4_start

axpy4_loop16:
	VLD1.P 16(R4), [V16.S4]
	VLD1.P 16(R4), [V17.S4]
	VLD1.P 16(R4), [V18.S4]
	VLD1.P 16(R4), [V19.S4]

	VLD1.P 16(R6), [V0.S4]
	VLD1.P 16(R6), [V1.S4]
	VLD1.P 16(R6), [V2.S4]
	VLD1.P 16(R6), [V3.S4]
	VFMLA V16.S4, V24.S4, V0.S4
	VFMLA V17.S4, V24.S4, V1.S4
	VFMLA V18.S4, V24.S4, V2.S4
	VFMLA V19.S4, V24.S4, V3.S4
	VST1.P [V0.S4, V1.S4], 32(R0)
	VST1.P [V2.S4, V3.S4], 32(R0)

	VLD1.P 16(R7), [V4.S4]
	VLD1.P 16(R7), [V5.S4]
	VLD1.P 16(R7), [V6.S4]
	VLD1.P 16(R7), [V7.S4]
	VFMLA V16.S4, V25.S4, V4.S4
	VFMLA V17.S4, V25.S4, V5.S4
	VFMLA V18.S4, V25.S4, V6.S4
	VFMLA V19.S4, V25.S4, V7.S4
	VST1.P [V4.S4, V5.S4], 32(R1)
	VST1.P [V6.S4, V7.S4], 32(R1)

	VLD1.P 16(R8), [V8.S4]
	VLD1.P 16(R8), [V9.S4]
	VLD1.P 16(R8), [V10.S4]
	VLD1.P 16(R8), [V11.S4]
	VFMLA V16.S4, V26.S4, V8.S4
	VFMLA V17.S4, V26.S4, V9.S4
	VFMLA V18.S4, V26.S4, V10.S4
	VFMLA V19.S4, V26.S4, V11.S4
	VST1.P [V8.S4, V9.S4], 32(R2)
	VST1.P [V10.S4, V11.S4], 32(R2)

	VLD1.P 16(R9), [V12.S4]
	VLD1.P 16(R9), [V13.S4]
	VLD1.P 16(R9), [V14.S4]
	VLD1.P 16(R9), [V15.S4]
	VFMLA V16.S4, V27.S4, V12.S4
	VFMLA V17.S4, V27.S4, V13.S4
	VFMLA V18.S4, V27.S4, V14.S4
	VFMLA V19.S4, V27.S4, V15.S4
	VST1.P [V12.S4, V13.S4], 32(R3)
	VST1.P [V14.S4, V15.S4], 32(R3)

	SUB $16, R5, R5
	CMP $16, R5
	BGE axpy4_loop16

axpy4_loop4_start:
	CMP $4, R5
	BLT axpy4_tail

axpy4_loop4:
	VLD1.P 16(R4), [V16.S4]
	VLD1.P 16(R6), [V0.S4]
	VFMLA V16.S4, V24.S4, V0.S4
	VST1.P [V0.S4], 16(R0)
	VLD1.P 16(R7), [V1.S4]
	VFMLA V16.S4, V25.S4, V1.S4
	VST1.P [V1.S4], 16(R1)
	VLD1.P 16(R8), [V2.S4]
	VFMLA V16.S4, V26.S4, V2.S4
	VST1.P [V2.S4], 16(R2)
	VLD1.P 16(R9), [V3.S4]
	VFMLA V16.S4, V27.S4, V3.S4
	VST1.P [V3.S4], 16(R3)
	SUB $4, R5, R5
	CMP $4, R5
	BGE axpy4_loop4

axpy4_tail:
	CBZ R5, axpy4_done
	FMOVS.P 4(R4), F16
	FMOVS.P 4(R6), F0
	FMULS F24, F16, F17
	FADDS F17, F0
	FMOVS.P F0, 4(R0)
	FMOVS.P 4(R7), F1
	FMULS F25, F16, F17
	FADDS F17, F1
	FMOVS.P F1, 4(R1)
	FMOVS.P 4(R8), F2
	FMULS F26, F16, F17
	FADDS F17, F2
	FMOVS.P F2, 4(R2)
	FMOVS.P 4(R9), F3
	FMULS F27, F16, F17
	FADDS F17, F3
	FMOVS.P F3, 4(R3)
	SUB $1, R5, R5
	B axpy4_tail

axpy4_done:
	RET

// Four f32 dot products against one f16 row. The f16 row is expanded once
// into V17/V18 and consumed by all four query heads before the next load.
// This is the compact-KV counterpart to dotF32x4.
// func dotF32F16x4NEON(q0, q1, q2, q3 *float32, x *uint16, n int) (s0, s1, s2, s3 float32)
TEXT ·dotF32F16x4NEON(SB), NOSPLIT|NOFRAME, $0-64
	MOVD q0+0(FP), R0
	MOVD q1+8(FP), R1
	MOVD q2+16(FP), R2
	MOVD q3+24(FP), R3
	MOVD x+32(FP), R4
	MOVD n+40(FP), R5
	LSR  $3, R5, R5

	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16
	CBZ  R5, dotf16x4_reduce

dotf16x4_loop8:
	VLD1.P 16(R4), [V16.H8]
	WORD   $0x0e217a11 // fcvtl  v17.4s, v16.4h
	WORD   $0x4e217a12 // fcvtl2 v18.4s, v16.8h

	VLD1.P 16(R0), [V19.S4]
	VLD1.P 16(R0), [V20.S4]
	VFMLA  V19.S4, V17.S4, V0.S4
	VFMLA  V20.S4, V18.S4, V1.S4

	VLD1.P 16(R1), [V19.S4]
	VLD1.P 16(R1), [V20.S4]
	VFMLA  V19.S4, V17.S4, V2.S4
	VFMLA  V20.S4, V18.S4, V3.S4

	VLD1.P 16(R2), [V19.S4]
	VLD1.P 16(R2), [V20.S4]
	VFMLA  V19.S4, V17.S4, V4.S4
	VFMLA  V20.S4, V18.S4, V5.S4

	VLD1.P 16(R3), [V19.S4]
	VLD1.P 16(R3), [V20.S4]
	VFMLA  V19.S4, V17.S4, V6.S4
	VFMLA  V20.S4, V18.S4, V7.S4

	SUB $1, R5, R5
	CBNZ R5, dotf16x4_loop8

dotf16x4_reduce:
	FMOVS $(1.0), F31
	VDUP  V31.S[0], V31.S4
	VFMLA V1.S4, V31.S4, V0.S4
	VFMLA V3.S4, V31.S4, V2.S4
	VFMLA V5.S4, V31.S4, V4.S4
	VFMLA V7.S4, V31.S4, V6.S4

	VMOV V0.S[0], R6
	VMOV V0.S[1], R7
	VMOV V0.S[2], R8
	VMOV V0.S[3], R9
	FMOVS R6, F24
	FMOVS R7, F20
	FMOVS R8, F21
	FMOVS R9, F22
	FADDS F20, F24
	FADDS F22, F21
	FADDS F21, F24

	VMOV V2.S[0], R6
	VMOV V2.S[1], R7
	VMOV V2.S[2], R8
	VMOV V2.S[3], R9
	FMOVS R6, F25
	FMOVS R7, F20
	FMOVS R8, F21
	FMOVS R9, F22
	FADDS F20, F25
	FADDS F22, F21
	FADDS F21, F25

	VMOV V4.S[0], R6
	VMOV V4.S[1], R7
	VMOV V4.S[2], R8
	VMOV V4.S[3], R9
	FMOVS R6, F26
	FMOVS R7, F20
	FMOVS R8, F21
	FMOVS R9, F22
	FADDS F20, F26
	FADDS F22, F21
	FADDS F21, F26

	VMOV V6.S[0], R6
	VMOV V6.S[1], R7
	VMOV V6.S[2], R8
	VMOV V6.S[3], R9
	FMOVS R6, F27
	FMOVS R7, F20
	FMOVS R8, F21
	FMOVS R9, F22
	FADDS F20, F27
	FADDS F22, F21
	FADDS F21, F27

	FMOVS F24, s0+48(FP)
	FMOVS F25, s1+52(FP)
	FMOVS F26, s2+56(FP)
	FMOVS F27, s3+60(FP)
	RET

// Four f32 AXPYs against one f16 row. It expands the shared V row once and
// applies all four attention weights while the converted values are live in
// NEON registers.
// func axpyF32F16x4NEON(out0, out1, out2, out3 *float32, a0, a1, a2, a3 float32, x *uint16, n int)
TEXT ·axpyF32F16x4NEON(SB), NOSPLIT|NOFRAME, $0-64
	MOVD out0+0(FP), R0
	MOVD out1+8(FP), R1
	MOVD out2+16(FP), R2
	MOVD out3+24(FP), R3
	MOVD R0, R6
	MOVD R1, R7
	MOVD R2, R8
	MOVD R3, R9
	FMOVS a0+32(FP), F24
	FMOVS a1+36(FP), F25
	FMOVS a2+40(FP), F26
	FMOVS a3+44(FP), F27
	MOVD x+48(FP), R4
	MOVD n+56(FP), R5
	LSR  $3, R5, R5
	VDUP V24.S[0], V24.S4
	VDUP V25.S[0], V25.S4
	VDUP V26.S[0], V26.S4
	VDUP V27.S[0], V27.S4
	CBZ  R5, axpyf16x4_done

axpyf16x4_loop8:
	VLD1.P 16(R4), [V16.H8]
	WORD   $0x0e217a11 // fcvtl  v17.4s, v16.4h
	WORD   $0x4e217a12 // fcvtl2 v18.4s, v16.8h

	VLD1.P 16(R6), [V0.S4]
	VLD1.P 16(R6), [V1.S4]
	VFMLA  V17.S4, V24.S4, V0.S4
	VFMLA  V18.S4, V24.S4, V1.S4
	VST1.P [V0.S4, V1.S4], 32(R0)

	VLD1.P 16(R7), [V2.S4]
	VLD1.P 16(R7), [V3.S4]
	VFMLA  V17.S4, V25.S4, V2.S4
	VFMLA  V18.S4, V25.S4, V3.S4
	VST1.P [V2.S4, V3.S4], 32(R1)

	VLD1.P 16(R8), [V4.S4]
	VLD1.P 16(R8), [V5.S4]
	VFMLA  V17.S4, V26.S4, V4.S4
	VFMLA  V18.S4, V26.S4, V5.S4
	VST1.P [V4.S4, V5.S4], 32(R2)

	VLD1.P 16(R9), [V6.S4]
	VLD1.P 16(R9), [V7.S4]
	VFMLA  V17.S4, V27.S4, V6.S4
	VFMLA  V18.S4, V27.S4, V7.S4
	VST1.P [V6.S4, V7.S4], 32(R3)

	SUB  $1, R5, R5
	CBNZ R5, axpyf16x4_loop8

axpyf16x4_done:
	RET
