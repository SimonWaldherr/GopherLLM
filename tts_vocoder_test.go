// The checked-in fixture contains only seeded random weights. It exercises
// both upsampling stages, residual branches and dilations without a model.
func TestTTSVocoderTinyReference(t *testing.T) {
	data, err := os.ReadFile("testdata/tts_vocoder.safetensors")
	if err != nil {
		t.Fatal(err)
	}
	ref, err := ParseSafetensors(data)
	if err != nil {
		t.Fatal(err)
	}
	cfg := ttsVITSConfig{
		FlowSize: 2, UpsampleInitialChannel: 8,
		UpsampleRates: []int{2, 2}, UpsampleKernelSizes: []int{4, 4},
		ResblockKernelSizes: []int{3, 5}, ResblockDilationSizes: [][]int{{1, 3}, {1, 3}},
		LeakyReLUSlope: .1,
	}
	ttsCheckVocoderReference(t, cfg, ref, ref)
}

// Optional independent reference generated by scripts/tts_vocoder_reference.py.
// No download, Python invocation or inference runtime is used by this test.
func TestTTSVocoderTorchReference(t *testing.T) {
	dir, reference := os.Getenv("GOPHERLLM_TTS_MODEL"), os.Getenv("GOPHERLLM_TTS_VOCODER_REFERENCE")
	if dir == "" || reference == "" {
		t.Skip("set GOPHERLLM_TTS_MODEL and GOPHERLLM_TTS_VOCODER_REFERENCE")
	}
	setPerformanceThreads(t, 8)
	configData, err := os.ReadFile(filepath.Join(dir, "config.json"))
	if err != nil {
		t.Fatal(err)
	}
	var cfg ttsVITSConfig
	if err := json.Unmarshal(configData, &cfg); err != nil {
		t.Fatal(err)
	}
	model, err := OpenMmap(filepath.Join(dir, "model.safetensors"))
	if err != nil {
		t.Fatal(err)
	}
	defer model.Close()
	file, err := ParseSafetensors(model.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	bytes, err := os.ReadFile(reference)
	if err != nil {
		t.Fatal(err)
	}
	ref, err := ParseSafetensors(bytes)
	if err != nil {
		t.Fatal(err)
	}
	ttsCheckVocoderReference(t, cfg, file, ref)
}

func ttsCheckVocoderReference(t *testing.T, cfg ttsVITSConfig, model, ref *SafetensorsFile) {
	t.Helper()
	weights := make(map[string]ttsWeight)
	for name, info := range model.Tensors {
		if strings.HasPrefix(name, "decoder.") {
			data, err := model.F32(name)
			if err != nil {
				t.Fatal(err)
			}
			weights[name] = ttsWeight{data: data, shape: info.Shape}
		}
	}
	latent, err := ref.F32("latent")
	if err != nil {
		t.Fatal(err)
	}
	shape := ref.Tensors["latent"].Shape
	if len(shape) != 2 {
		t.Fatal("invalid reference latent")
	}
	want, err := ref.F32("waveform")
	if err != nil {
		t.Fatal(err)
	}
	before := slices.Clone(latent)
	got, err := ttsVocode(context.Background(), weights, cfg, ttsMatrix{data: latent, channels: shape[0], length: shape[1]})
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != len(want) {
		t.Fatalf("samples %d, want %d", len(got), len(want))
	}
	if !slices.Equal(latent, before) {
		t.Fatal("vocoder changed its latent input")
	}
	var maxError, squared float64
	for i, value := range want {
		diff := math.Abs(float64(got[i] - value))
		maxError = max(maxError, diff)
		squared += diff * diff
		if math.IsNaN(float64(got[i])) || math.IsInf(float64(got[i]), 0) || diff > 2e-5 {
			t.Fatalf("sample%d: %g, want %g; difference %g", i, got[i], value, diff)
		}
	}
	t.Logf("%d samples: max error %.8g, RMSE %.8g", len(got), maxError, math.Sqrt(squared/float64(len(got))))
}
