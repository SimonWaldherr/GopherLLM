// Command genapi regenerates the public facade from the engine's exported API.
// Run it from the module root with go generate .
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const engineImport = "github.com/SimonWaldherr/GopherLLM/internal/engine"

func main() {
	check := flag.Bool("check", false, "check that the public facade is up to date without writing files")
	flag.Parse()
	if err := generate(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(check bool) error {
	files, err := filepath.Glob("internal/engine/*.go")
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("run genapi from the module root: no engine sources found")
	}
	fset := token.NewFileSet()
	imports := map[string]string{"engineimpl": engineImport}
	seen := map[string]bool{}
	var declarations bytes.Buffer
	for _, name := range files {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, name, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		fileImports := map[string]string{}
		for _, spec := range file.Imports {
			path, err := strconv.Unquote(spec.Path.Value)
			if err != nil {
				return err
			}
			alias := filepath.Base(path)
			if spec.Name != nil {
				alias = spec.Name.Name
			}
			fileImports[alias] = path
		}
		useImports := func(node ast.Node) error {
			var conflict error
			ast.Inspect(node, func(node ast.Node) bool {
				selector, ok := node.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				base, ok := selector.X.(*ast.Ident)
				if !ok {
					return true
				}
				path, ok := fileImports[base.Name]
				if !ok {
					return true
				}
				if previous, ok := imports[base.Name]; ok && previous != path {
					conflict = fmt.Errorf("conflicting facade import %s: %s and %s", base.Name, previous, path)
				}
				imports[base.Name] = path
				return true
			})
			return conflict
		}
		for _, declaration := range file.Decls {
			switch declaration := declaration.(type) {
			case *ast.FuncDecl:
				if declaration.Recv != nil || !declaration.Name.IsExported() || seen[declaration.Name.Name] {
					continue
				}
				seen[declaration.Name.Name] = true
				if err := useImports(declaration.Type); err != nil {
					return err
				}
				writeDoc(&declarations, declaration.Doc)
				arguments := []string{}
				for _, field := range declaration.Type.Params.List {
					if len(field.Names) == 0 {
						field.Names = []*ast.Ident{ast.NewIdent(fmt.Sprintf("arg%d", len(arguments)))}
					}
					for i, name := range field.Names {
						if name.Name == "_" {
							name = ast.NewIdent(fmt.Sprintf("arg%d", len(arguments)))
							field.Names[i] = name
						}
						arguments = append(arguments, name.Name)
					}
					if _, variadic := field.Type.(*ast.Ellipsis); variadic {
						arguments[len(arguments)-1] += "..."
					}
				}
				if err := format.Node(&declarations, fset, &ast.FuncDecl{Name: declaration.Name, Type: declaration.Type}); err != nil {
					return err
				}
				declarations.WriteString(" {\n")
				if declaration.Type.Results != nil && len(declaration.Type.Results.List) > 0 {
					declarations.WriteString("return ")
				}
				fmt.Fprintf(&declarations, "engineimpl.%s%s(%s)\n}\n\n", declaration.Name.Name, typeArguments(declaration.Type.TypeParams), strings.Join(arguments, ", "))
			case *ast.GenDecl:
				for i, spec := range declaration.Specs {
					doc := declaration.Doc
					if i > 0 {
						doc = nil
					}
					switch spec := spec.(type) {
					case *ast.TypeSpec:
						if !spec.Name.IsExported() || seen[spec.Name.Name] {
							continue
						}
						seen[spec.Name.Name] = true
						if spec.Doc != nil {
							doc = spec.Doc
						}
						writeDoc(&declarations, doc)
						fmt.Fprintf(&declarations, "type %s", spec.Name.Name)
						if spec.TypeParams != nil {
							return fmt.Errorf("generic type %s needs an explicit facade alias", spec.Name.Name)
						}
						fmt.Fprintf(&declarations, " = engineimpl.%s\n\n", spec.Name.Name)
					case *ast.ValueSpec:
						for _, name := range spec.Names {
							if !name.IsExported() || seen[name.Name] {
								continue
							}
							seen[name.Name] = true
							if spec.Doc != nil {
								doc = spec.Doc
							}
							writeDoc(&declarations, doc)
							fmt.Fprintf(&declarations, "%s %s = engineimpl.%s\n\n", declaration.Tok, name.Name, name.Name)
						}
					}
				}
			}
		}
	}
	var output bytes.Buffer
	output.WriteString("// Code generated by go generate .; DO NOT EDIT.\n\npackage gopherllm\n\nimport (\n")
	aliases := make([]string, 0, len(imports))
	for alias := range imports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	for _, alias := range aliases {
		if alias != "engineimpl" {
			if alias == filepath.Base(imports[alias]) {
				fmt.Fprintf(&output, "%q\n", imports[alias])
			} else {
				fmt.Fprintf(&output, "%s %q\n", alias, imports[alias])
			}
		}
	}
	fmt.Fprintf(&output, "\nengineimpl %q\n", engineImport)
	output.WriteString(")\n\n")
	output.Write(declarations.Bytes())
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return fmt.Errorf("format facade: %w", err)
	}
	if check {
		current, err := os.ReadFile("api_generated.go")
		if err != nil {
			return err
		}
		// Git may check out CRLF on Windows; formatting always emits LF.
		if !bytes.Equal(bytes.ReplaceAll(current, []byte("\r\n"), []byte("\n")), formatted) {
			return fmt.Errorf("public facade is out of date; run go generate .")
		}
		return nil
	}
	return os.WriteFile("api_generated.go", formatted, 0644)
}

func writeDoc(out *bytes.Buffer, doc *ast.CommentGroup) {
	if doc != nil {
		for _, comment := range doc.List {
			out.WriteString(comment.Text)
			out.WriteByte('\n')
		}
	}
}

func typeArguments(parameters *ast.FieldList) string {
	if parameters == nil {
		return ""
	}
	names := []string{}
	for _, field := range parameters.List {
		for _, name := range field.Names {
			names = append(names, name.Name)
		}
	}
	return "[" + strings.Join(names, ", ") + "]"
}
